import assert from 'node:assert/strict';
import { freshAdjustments, copyAdjustments, applyColors, applyLocal, blendChannel, sampleWhiteBalance } from '../../web/src/adjustments.js';
import { writePreset, readPresets } from '../../web/src/saved-presets.js';
import { freshSettings } from '../../web/src/effects.js';
const flat = (w, h, rgb = [128, 128, 128, 255]) => new Uint8ClampedArray(Array.from({ length: w * h }, () => rgb).flat());
const place = { x: 0, y: 0, fullWidth: 100, fullHeight: 80 };
const geometry = { originalWidth: 100, originalHeight: 80, crop: { x: 0, y: 0, w: 100, h: 80 } };
const oval = { id: 'test', name: 'Oval', type: 'ellipse', enabled: true, blend: 'soft-light', opacity: 100, x: .5, y: .5, rx: .3, ry: .3, softness: 75, tone: 70 };
for (const mode of ['soft-light', 'overlay']) {
  for (const b of [0, .1, .25, .5, .75, 1]) assert.equal(blendChannel(b, .5, mode), b, 'neutral grey stays neutral');
}
assert.equal(blendChannel(.25, 1, 'soft-light'), .5);
assert.equal(blendChannel(.25, 0, 'soft-light'), .0625);
assert.equal(blendChannel(.25, 1, 'overlay'), .5);
assert.equal(blendChannel(.75, 0, 'overlay'), .5);
const neutral = flat(100, 80), lit = applyLocal(neutral.slice(), 100, 80, [oval], geometry, place);
const center = (40 * 100 + 50) * 4;
assert.ok(lit[center] > 150); assert.equal(lit[0], 128, 'outside mask unchanged');
assert.deepEqual(applyLocal(neutral.slice(), 100, 80, [{ ...oval, opacity: 0 }], geometry, place), neutral);
assert.deepEqual(applyLocal(neutral.slice(), 100, 80, [{ ...oval, enabled: false }], geometry, place), neutral);
assert.ok(applyLocal(neutral.slice(), 100, 80, [{ ...oval, tone: -70 }], geometry, place)[center] < 100);
// Independent band and cropped evaluations must be byte-identical to a full-resolution frame.
const band = applyLocal(flat(100, 17), 100, 17, [oval], geometry, { ...place, y: 30 });
assert.deepEqual(band, lit.slice(30 * 400, 47 * 400));
const cut = { x: 35, y: 20, w: 40, h: 30 };
const cropped = applyLocal(flat(cut.w, cut.h), cut.w, cut.h, [oval], { ...geometry, crop: cut }, { x: 0, y: 0, fullWidth: cut.w, fullHeight: cut.h });
for (let y = 0; y < cut.h; y++) assert.deepEqual(cropped.slice(y * cut.w * 4, (y + 1) * cut.w * 4), lit.slice(((cut.y + y) * 100 + cut.x) * 4, ((cut.y + y) * 100 + cut.x + cut.w) * 4));
const brush = { ...oval, type: 'brush', strokes: [{ mode: 'dodge', radius: .12, softness: 70, strength: 60, points: [[.2, .5], [.8, .5]] }] };
const painted = applyLocal(neutral.slice(), 100, 80, [brush], geometry, place);
assert.ok(painted[center] > 150, 'continuous stroke fills between sparse events');
assert.equal(painted[0], 128);
assert.deepEqual(applyLocal(flat(100, 17), 100, 17, [brush], geometry, { ...place, y: 30 }), painted.slice(30 * 400, 47 * 400));
const dense = structuredClone(brush); dense.strokes[0].points.splice(1, 0, [.5, .5]);
assert.deepEqual(applyLocal(neutral.slice(), 100, 80, [dense], geometry, place), painted, 'event rate does not affect coverage');
brush.strokes.push({ ...brush.strokes[0], mode: 'erase', strength: 100, softness: 0 });
assert.equal(applyLocal(neutral.slice(), 100, 80, [brush], geometry, place)[center], 128, 'erase returns paint to neutral');
const alpha = flat(100, 80, [128, 128, 128, 40]); alpha.set([9, 8, 7, 0], center);
const transparent = applyLocal(alpha.slice(), 100, 80, [oval], geometry, place);
assert.deepEqual([...transparent.slice(center, center + 4)], [9, 8, 7, 0]);
assert.ok(transparent.every((v, i) => i % 4 !== 3 || v === alpha[i]), 'alpha preserved');
const a = freshAdjustments();
assert.deepEqual(applyColors(neutral.slice(), a), neutral);
const image = { width: 5, height: 5, data: flat(5, 5, [160, 120, 80, 255]) };
a.whiteBalance.enabled = true; a.whiteBalance.gains = sampleWhiteBalance(image, 2, 2);
const corrected = applyColors(image.data.slice(), a);
assert.equal(corrected[0], corrected[1]); assert.equal(corrected[1], corrected[2]);
assert.throws(() => sampleWhiteBalance({ width: 5, height: 5, data: flat(5, 5, [255, 255, 255, 255]) }, 2, 2), /neutral/);
const color = freshAdjustments(); color.colors.enabled = true; color.colors.ranges[1].saturation = -100;
const out = applyColors(new Uint8ClampedArray([200, 120, 40, 255, 40, 200, 40, 255, 128, 128, 128, 255]), color);
assert.equal(out[0], out[1]); assert.equal(out[1], out[2], 'orange desaturated');
assert.deepEqual([...out.slice(4)], [40, 200, 40, 255, 128, 128, 128, 255], 'green and neutral pixels unchanged');
const storage = { getItem: () => storage.value, setItem: (_, value) => storage.value = value };
color.layers.push(oval);
writePreset(storage, [], 'Colors', freshSettings(), 1, color);
assert.deepEqual(readPresets(storage)[0].adjustments.colors, color.colors);
assert.deepEqual(readPresets(storage)[0].adjustments.layers, [], 'image-specific masks excluded from reusable looks');
assert.equal(copyAdjustments({ whiteBalance: { gains: [NaN, 90, -30] } }).whiteBalance.gains[1], 4);
console.log('PASS: blend reference values, mask boundaries, crop/band equivalence, stroke spacing/erase, alpha, WB, selective color, preset isolation.');
